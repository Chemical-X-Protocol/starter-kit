/**
 * Chemical X Protocol: renders a dispatch run plan (team-dispatch-v2.js) as a Claude Code Workflow
 * script (#2494). chemx only renders the script; the host runs it (the Workflow tool's scriptPath).
 * Line 1 is the meta export as a pure literal. The data (RUN, TASKS, LANES, GATE) is JSON, and the
 * logic is the versioned SCRIPT_BODY template. No timestamps: one plan renders byte-identical text.
 */
import { TEMPLATE_VERSION, SCRIPT_BODY } from './dispatch-templates/dispatch-v1.js';
import { renderTaskPrompts, renderGatePrompt } from './team-dispatch-prompts.js';
import { summarizeSkipped } from './team-dispatch-render.js';

const TITLE_LIMIT = 120;

const clip = (text, limit) => {
  const value = String(text || '').replace(/\s+/g, ' ').trim();
  const isLong = value.length > limit;
  return isLong ? `${value.slice(0, limit - 3)}...` : value;
};

const stage = (route) => ({ model: route.model, effort: route.effort });

/** The TASKS entries the script reads: routing per stage plus the rendered prompts. */
export const scriptTasks = (plan) => plan.tasks.map((task) => ({
  id: task.id,
  title: clip(task.title, TITLE_LIMIT),
  needs: task.needs,
  handle: task.handle,
  target: task.target,
  files: task.files,
  build: stage(task.build),
  review: stage(task.review),
  repair: stage(task.repair),
  prompts: renderTaskPrompts(task, plan)
}));

const metaFor = (plan) => {
  const count = `${plan.tasks.length} task(s) in ${plan.lanes.length} lane(s)`;
  return {
    name: `chemx-${plan.run}`,
    description: `chemx team dispatch run ${plan.run}: ${count}; per task build, review on the same tier, light repair when the review finds issues; then a light gate (${TEMPLATE_VERSION})`,
    phases: [
      { title: 'Build', detail: 'one builder per task on its routed model and effort; lanes run at the same time, tasks in a lane one after another' },
      { title: 'Review', detail: 'read-only reviewer per task: chemx test --changed --depth=2, chemx check, acceptance' },
      { title: 'Repair', detail: 'light repair when a review reports issues; it takes the task over with chemx team task handoff' },
      { title: 'Gate', detail: 'close reviewed tasks, find and record the workflow run, chemx team audit-run, post a summary' }
    ]
  };
};

/** The Workflow script text, or null when the plan has no tasks (nothing to run). */
export const renderRunScript = (plan) => {
  const hasTasks = plan.tasks.length > 0;
  if (!hasTasks) return null;
  const gate = { handle: plan.gate.handle, model: plan.gate.model, effort: plan.gate.effort, prompt: renderGatePrompt(plan) };
  const skipped = summarizeSkipped(plan.skipped).map((line) => `// skipped: ${line}`);
  return [
    `export const meta = ${JSON.stringify(metaFor(plan))}`,
    '',
    `// Generated by chemx team dispatch (template ${TEMPLATE_VERSION}) for run ${plan.run}. chemx rendered this script; the host runs it.`,
    `// After the run: chemx team dispatch --find-run=${plan.run}, then chemx team audit-run --run=<workflow run id>.`,
    ...skipped,
    `const RUN = ${JSON.stringify(plan.run)}`,
    `const TASKS = ${JSON.stringify(scriptTasks(plan), null, 2)}`,
    `const LANES = ${JSON.stringify(plan.lanes)}`,
    `const GATE = ${JSON.stringify(gate, null, 2)}`,
    SCRIPT_BODY
  ].join('\n');
};
